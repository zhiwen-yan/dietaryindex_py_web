def _family_lookup() -> dict[str, dict]:
    return {row["family_key"]: row for row in INDEX_FAMILY_REGISTRY}


def get_index_spec_table(*, include_planned: bool = True) -> pd.DataFrame:
    """Return the canonical index registry as a DataFrame."""
    family_map = _family_lookup()
    rows = []
    for item in INDEX_SPEC_REGISTRY:
        if not include_planned and item["status"] != "active":
            continue
        row = deepcopy(item)
        family = family_map[row["family_key"]]
        row["family_label_zh"] = family["label_zh"]
        row["family_label_en"] = family["label_en"]
        row["supported_modes"] = "|".join(row["supported_modes"])
        rows.append(row)
    return pd.DataFrame(rows)


def get_family_blueprint_table(*, include_planned: bool = True) -> pd.DataFrame:
    """Return the active + planned family roadmap."""
    rows = []
    for item in INDEX_FAMILY_REGISTRY:
        if not include_planned and item["status"] != "active":
            continue
        row = deepcopy(item)
        row["member_keys"] = "|".join(
            spec["index_key"]
            for spec in INDEX_SPEC_REGISTRY
            if spec["family_key"] == item["family_key"]
        )
        rows.append(row)
    return pd.DataFrame(rows)


def get_output_naming_rules() -> pd.DataFrame:
    """Return the shared output naming convention table."""
    return pd.DataFrame(deepcopy(OUTPUT_NAMING_RULES))


